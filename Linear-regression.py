# calculate the loss
def helpme_loss(w, b, x, y):
    total = 0
    for i in range(0, x.shape[0]):
        cost = ((w * x[i] + b) - y[i]) ** 2
        total += cost
    final_cost = (1 / (2 * x.shape[0])) * total
    return final_cost


