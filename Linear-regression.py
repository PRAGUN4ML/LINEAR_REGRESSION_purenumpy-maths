def compute_partial(w, b, x, y):
    partial_d_w = 0
    for i in range(0, x.shape[0]):
        temp = ((w * x[i] + b) - y[i]) * x[i]
        partial_d_w += temp
    partial_d_b = 0
    for i in range(0, x.shape[0]):
        tempu = (w * x[i] + b) - y[i]
        partial_d_b += tempu
    f_partial_w = (1 / (x.shape[0])) * partial_d_w
    f_partial_b = (1 / (x.shape[0])) * partial_d_b
    return f_partial_w, f_partial_b


print("äfter gradient lets do the descent")

losslist = []
epochlist = []


def lets_descent(w, b, x, y):
    epochs = int(input("tell epochs:"))
    for i in range(epochs):
        epochlist.append(i)
    l_r = 0.0006
    for i in range(0, epochs):
        respective_loss_forepoch = helpme_loss(w, b, x, y)
        losslist.append(respective_loss_forepoch)
        w, b = (
            w - l_r * compute_partial(w, b, x, y)[0],
            b - l_r * compute_partial(w, b, x, y)[1],
        )
    return w, b, losslist, epochlist


